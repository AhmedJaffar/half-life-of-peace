"""Shared utilities for the Half-Life of Peace data pipeline.

Design goals
------------
* **Idempotent / resumable** - every raw HTTP response is written verbatim
  (as JSON) under ``data/raw/`` before it is parsed.  Re-running the pipeline
  replays the cache and performs zero network requests unless ``refresh=True``.
* **Polite** - a single global rate limiter caps the whole process at
  ``RATE_LIMIT_PER_SEC`` requests/second across all worker threads, every
  request carries an identifying User-Agent, and 429/5xx responses are retried
  with exponential backoff (honouring ``Retry-After``).
* **Auditable** - cache envelopes record URL, HTTP status and fetch timestamp,
  so the provenance of every number in ``data/processed`` is traceable.

Layout (owned by this pipeline):
    data/raw/langlinks/        raw MediaWiki langlinks responses
    data/raw/langlinks.json    consolidated langlinks mapping
    data/raw/pageviews/        raw Wikimedia pageviews responses
    data/raw/ucdp/             UCDP GED zip + extracted CSV
    data/processed/            tidy outputs
    data/README.md             data dictionary (generated by src/report.py)

``data/events/`` belongs to the event-curation task and is never written here.
"""
from __future__ import annotations

import hashlib
import json
import os
import random
import threading
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, Optional, Tuple

import requests

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = PROJECT_ROOT / "data"
DATA_RAW = DATA_DIR / "raw"
DATA_PROCESSED = DATA_DIR / "processed"
# Owned by the event-curation task (task-2).  This pipeline only ever READS it,
# and tolerates it being absent.
DATA_EVENTS = DATA_DIR / "events"

RETRIEVAL_DATE = "2026-11-07"

try:  # single source of truth for the UA lives in config.py
    from . import config as _config

    USER_AGENT = _config.USER_AGENT
except ImportError:  # pragma: no cover
    USER_AGENT = (
        "HalfLifeOfPeace/0.1 (https://github.com/AhmedJaffar/half-life-of-peace; "
        "research; contact: ahmedjaffar.ca)"
    )

MAX_WORKERS = 5
RATE_LIMIT_PER_SEC = 5.0
REQUEST_TIMEOUT = 90
DEFAULT_RETRIES = 6


# ---------------------------------------------------------------------------
# small helpers
# ---------------------------------------------------------------------------
def ensure_dirs(*paths: Any) -> None:
    for path in paths:
        Path(path).mkdir(parents=True, exist_ok=True)


def sha1_key(text: str) -> str:
    return hashlib.sha1(text.encode("utf-8")).hexdigest()


def utc_now_iso() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def atomic_write_json(path: Any, obj: Any) -> None:
    """Write JSON atomically (tmp file + os.replace) so a crash cannot leave
    a half-written cache file behind."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    with open(tmp, "w", encoding="utf-8") as fh:
        json.dump(obj, fh, ensure_ascii=False, indent=2, sort_keys=True)
        fh.flush()
        os.fsync(fh.fileno())
    os.replace(tmp, path)


def read_json(path: Any) -> Any:
    with open(path, "r", encoding="utf-8") as fh:
        return json.load(fh)


def log(msg: str) -> None:
    print("[{}] {}".format(datetime.now().strftime("%H:%M:%S"), msg), flush=True)


# ---------------------------------------------------------------------------
# network accounting
# ---------------------------------------------------------------------------
class Stats:
    """Thread-safe counters describing what the HTTP layer did."""

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self.network_requests = 0
        self.cache_hits = 0
        self.retries = 0
        self.status_counts: Dict[int, int] = {}
        self.bytes_downloaded = 0

    def inc_network(self, nbytes: int = 0) -> None:
        with self._lock:
            self.network_requests += 1
            self.bytes_downloaded += nbytes

    def inc_cache(self) -> None:
        with self._lock:
            self.cache_hits += 1

    def inc_retry(self) -> None:
        with self._lock:
            self.retries += 1

    def add_status(self, status: int) -> None:
        with self._lock:
            self.status_counts[status] = self.status_counts.get(status, 0) + 1

    def as_dict(self) -> Dict[str, Any]:
        with self._lock:
            return {
                "network_requests": self.network_requests,
                "cache_hits": self.cache_hits,
                "retries": self.retries,
                "status_counts": {str(k): v for k, v in sorted(self.status_counts.items())},
                "bytes_downloaded": self.bytes_downloaded,
            }


# ---------------------------------------------------------------------------
# polite rate limiting + cached HTTP
# ---------------------------------------------------------------------------
class RateLimiter:
    """Global, cross-thread request scheduler.

    Guarantees that consecutive *network* requests are spaced at least
    ``1/rate`` seconds apart, i.e. at most ``rate`` requests/second overall no
    matter how many worker threads are running.
    """

    def __init__(self, rate: float = RATE_LIMIT_PER_SEC) -> None:
        self._interval = 1.0 / max(float(rate), 0.001)
        self._lock = threading.Lock()
        self._next_allowed = 0.0

    def wait(self) -> None:
        with self._lock:
            now = time.monotonic()
            delay = max(0.0, self._next_allowed - now)
            self._next_allowed = max(now, self._next_allowed) + self._interval
        if delay > 0:
            time.sleep(delay)


class HttpCache:
    """Cached JSON GETs with retries, backoff and a shared rate limiter.

    Cache entries are envelopes::

        {"url": ..., "status": 200, "fetched_at": ..., "meta": {...}, "body": {...}}

    ``meta`` lets callers record which (article, language, date range) the raw
    response belongs to, so the processed tables can be rebuilt from the cache
    alone on a subsequent run.
    """

    def __init__(
        self,
        cache_root: Any = DATA_RAW,
        refresh: bool = False,
        rate: float = RATE_LIMIT_PER_SEC,
        stats: Optional[Stats] = None,
    ) -> None:
        self.cache_root = Path(cache_root)
        self.refresh = refresh
        self.limiter = RateLimiter(rate)
        self.stats = stats or Stats()
        self._local = threading.local()
        ensure_dirs(self.cache_root)

    # -- per-thread session (requests.Session is not guaranteed thread-safe) --
    def _session(self) -> requests.Session:
        session = getattr(self._local, "session", None)
        if session is None:
            session = requests.Session()
            session.headers.update(
                {
                    "User-Agent": USER_AGENT,
                    "Accept": "application/json",
                    "Accept-Encoding": "gzip, deflate",
                }
            )
            self._local.session = session
        return session

    def load_cached(self, cache_path: Any) -> Optional[Dict[str, Any]]:
        if self.refresh:
            return None
        path = Path(cache_path)
        if not path.exists():
            return None
        try:
            return read_json(path)
        except (ValueError, OSError):
            return None

    def get_json(
        self,
        url: str,
        cache_path: Any,
        meta: Optional[Dict[str, Any]] = None,
        retries: int = DEFAULT_RETRIES,
        cache_statuses: Tuple[int, ...] = (200, 404),
        timeout: int = REQUEST_TIMEOUT,
    ) -> Tuple[Dict[str, Any], bool]:
        """Return ``(envelope, from_cache)``.

        Successful (``200``) and permanently-missing (``404``) responses are
        cached verbatim.  ``429``/``5xx`` are retried with exponential backoff;
        any other status is returned uncached so callers can decide (e.g. a
        ``400`` triggers the chunked date-range fallback in pageviews.py).
        """
        cached = self.load_cached(cache_path)
        if cached is not None:
            self.stats.inc_cache()
            return cached, True

        session = self._session()
        last_error = None
        for attempt in range(retries + 1):
            self.limiter.wait()
            self.stats.inc_network()
            try:
                resp = session.get(url, timeout=timeout, allow_redirects=True)
            except requests.RequestException as exc:  # network layer failure
                last_error = repr(exc)
                if attempt < retries:
                    self._sleep_backoff(attempt)
                    self.stats.inc_retry()
                    continue
                raise RuntimeError("request failed after retries: {} ({})".format(url, exc)) from exc

            self.stats.add_status(resp.status_code)

            if resp.status_code in cache_statuses:
                body: Any = None
                if resp.status_code == 200:
                    try:
                        body = resp.json()
                    except ValueError:
                        body = None
                envelope = {
                    "url": url,
                    "status": resp.status_code,
                    "fetched_at": utc_now_iso(),
                    "meta": meta or {},
                    "body": body,
                }
                ensure_dirs(Path(cache_path).parent)
                atomic_write_json(cache_path, envelope)
                return envelope, False

            if resp.status_code in (429, 500, 502, 503, 504, 408):
                last_error = "HTTP {}".format(resp.status_code)
                if attempt < retries:
                    self._sleep_backoff(attempt, resp)
                    self.stats.inc_retry()
                    continue

            # non-retryable, or retries exhausted: return ephemeral envelope
            return (
                {
                    "url": url,
                    "status": resp.status_code,
                    "fetched_at": utc_now_iso(),
                    "meta": meta or {},
                    "body": None,
                    "text": resp.text[:400],
                },
                False,
            )

        return (
            {
                "url": url,
                "status": -1,
                "fetched_at": utc_now_iso(),
                "meta": meta or {},
                "body": None,
                "error": last_error,
            },
            False,
        )

    @staticmethod
    def _sleep_backoff(attempt: int, resp: Optional[requests.Response] = None) -> None:
        delay: Optional[float] = None
        if resp is not None:
            retry_after = resp.headers.get("Retry-After")
            if retry_after:
                try:
                    delay = float(retry_after)
                except ValueError:
                    delay = None
        if delay is None:
            delay = min(2 ** attempt, 30) * (0.5 + random.random())
        time.sleep(min(max(delay, 0.5), 60.0))
